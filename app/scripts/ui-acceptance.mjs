import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { launchBrowser } from './ui-browser.mjs';
import { createUiFixture, serveUiFixture, waitForUiRequest } from './ui-fixture.mjs';

const out = resolve(import.meta.dirname, '../.wrangler/tmp/ui-acceptance');
mkdirSync(out, { recursive: true });
const server = await serveUiFixture();
let browser;
const results = [];
try {
  browser = await launchBrowser();
  const { cdp } = browser;
  const { targetId } = await cdp.send('Target.createTarget', { url: 'about:blank' });
  const { sessionId } = await cdp.send('Target.attachToTarget', { targetId, flatten: true });
  await cdp.send('Page.enable', {}, sessionId);
  await cdp.send('Runtime.enable', {}, sessionId);
  await cdp.send('Page.setInterceptFileChooserDialog', { enabled: true }, sessionId);
  const read = expression => cdp.evaluate(sessionId, expression);
  const until = expression => cdp.until(sessionId, expression);
  const click = selector => cdp.click(sessionId, selector);
  const set = (selector, text) => read(`(() => { const input = document.querySelector(${JSON.stringify(selector)}); input.value = ${JSON.stringify(text)}; input.dispatchEvent(new Event('input', { bubbles: true })); })()`);
  const choose = (selector, value) => read(`(() => { const input = document.querySelector(${JSON.stringify(selector)}); input.value = ${JSON.stringify(value)}; input.dispatchEvent(new Event('change', { bubbles: true })); })()`);
  const capture = async name => {
    await read('document.querySelector(".dashboard-pool-card").scrollIntoView({ block: "start", behavior: "instant" }); new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))');
    const { data } = await cdp.send('Page.captureScreenshot', { format: 'png' }, sessionId);
    writeFileSync(join(out, name + '.png'), Buffer.from(data, 'base64'));
  };
  for (const width of [375, 1440]) {
    Object.assign(server.fixture, createUiFixture());
    server.fixture.poolContents.ip_pool_default = '# 保留标题\n203.0.113.10:443,AS64500,JP,v4 # 保留备注\n203.0.113.10:8443,AS64500,JP,v4 # 其他端口';
    await cdp.send('Emulation.setDeviceMetricsOverride', { width, height: 1000, mobile: width < 768, deviceScaleFactor: 1 }, sessionId);
    await cdp.send('Page.navigate', { url: server.base }, sessionId);
    await until('document.querySelector("#ip-input") && document.querySelector("#log-window").textContent.includes("就绪") && document.querySelectorAll("#status-table .status-badge.ok").length === 2');
    await read('window.__confirmAnswer = true; window.confirm = () => window.__confirmAnswer');
    assert.equal(await read('Boolean(document.querySelector("#pool-editor, [data-action=overwrite-input], [data-action=manage-inventory]"))'), false);
    assert.ok(await read('document.querySelector("#ip-input").placeholder.includes("[2001:db8::1]:8443")'));
    assert.ok(await read('document.querySelector(".console-config").open && document.querySelector(".console-settings").textContent.includes("并发")'));
    assert.ok(await read('document.querySelector(".console-colo").textContent.includes("NRT")'));
    assert.ok(await read('[...document.querySelectorAll(".exit-detail .exit-tag")].some(item => item.textContent.includes("San Jose"))'));
    await capture('input-' + width);
    await click('[aria-label="筛选用法"]');
    assert.ok(await read('document.querySelector(".pool-filter-row .pool-help-content").textContent.includes("备注")'));
    await capture('help-' + width);
    await click('[aria-label="筛选用法"]');
    const sourceStart = server.requests.length;
    await click('[data-action=load-pool]');
    await until('document.querySelector("#ip-input").value.includes("保留备注") && !document.querySelector("[data-action=load-pool]").disabled');
    const original = '203.0.113.10:443,AS64500,JP,v4 # 本地备注\n203.0.113.20:443,AS64500,US,v4 # 美国\n203.0.113.30:443,AS64500,KR,v4';
    const file = join(out, 'import-' + width + '.txt'); writeFileSync(file, original);
    const chooser = cdp.wait(sessionId, 'Page.fileChooserOpened');
    await click('[data-action=upload-file]');
    const { backendNodeId } = await chooser;
    await cdp.send('DOM.setFileInputFiles', { files: [file], backendNodeId }, sessionId);
    await until('document.querySelector("#ip-input").value.includes("本地备注") && !document.querySelector("[data-action=load-pool]").disabled');
    await set('#draft-filter', 'country:US');
    await until('document.querySelector("#ip-input").value.includes("203.0.113.20") && !document.querySelector("#ip-input").value.includes("203.0.113.10")');
    assert.equal(await read('document.querySelector("#ip-input").readOnly'), true);
    const checkStart = server.requests.length;
    await click('[aria-label="批量检测导入草稿"]');
    await until('!document.querySelector("[aria-label=停止批量检测]") && document.querySelector("[aria-label=检测结果分类]")?.textContent.includes("可用 1")');
    assert.deepEqual(server.requests.slice(checkStart).filter(item => item.path === '/api/check').map(item => item.input.proxyip), ['203.0.113.20:443']);
    await click('[data-action=view-draft]'); await set('#draft-filter', '');
    await until('document.querySelector("#ip-input").value.includes("本地备注")');
    assert.equal(await read('document.querySelector("#ip-input").value'), original);
    await click('[aria-label="批量检测导入草稿"]');
    await until('!document.querySelector("[aria-label=停止批量检测]") && document.querySelector("[aria-label=检测结果分类]")?.textContent.includes("可用 3")');
    await set('#draft-filter', 'country:US');
    await until('document.querySelectorAll(".pool-result-list li input").length === 3');
    await set('#draft-filter', '');
    await click('[aria-label="选择 203.0.113.10:443"]');
    server.fixture.executionColo = 'ICN';
    await set('#lookup-domain', '203.0.113.77:443');
    await click('[aria-label=探测]');
    await until('document.querySelector(".console-colo").textContent.includes("ICN")');
    server.fixture.executionColo = 'NRT';
    await click('[data-action=view-draft]');
    await click('[aria-label="批量检测导入草稿"]');
    await until('!document.querySelector("[aria-label=停止批量检测]") && document.querySelector("[aria-label=检测结果分类]")?.textContent.includes("可用 3")');
    assert.equal(await read('document.querySelector("[data-action=retain-results]").disabled'), true, '相同输入重新检测沿用了旧勾选');
    assert.ok(await read('document.querySelector(".console-colo").textContent.includes("NRT")'));
    await click('[aria-label="选择 203.0.113.10:443"]');
    await click('[aria-label="选择 203.0.113.30:443"]');
    await capture('results-' + width);
    await click('[data-action=retain-results]');
    await until('!document.querySelector(".pool-report")');
    assert.ok(await read('document.querySelector("#ip-input").value.includes("203.0.113.10") && document.querySelector("#ip-input").value.includes("203.0.113.30") && !document.querySelector("#ip-input").value.includes("203.0.113.20")'));
    assert.equal(server.requests.slice(sourceStart).filter(item => item.method === 'PUT').length, 0, '整理和保留结果写了库存');
    const appendStart = server.requests.length;
    await click('[data-action=append-pool]');
    await waitForUiRequest(server.requests, appendStart, '/api/pools/ip_pool_default', 'PUT', 200);
    await until('!document.querySelector("[data-action=append-pool]").disabled');
    assert.deepEqual(server.requests.slice(appendStart).filter(item => item.path.startsWith('/api/pools')).map(item => item.method), ['PUT']);
    assert.ok(server.fixture.poolContents.ip_pool_default.includes('其他端口'));
    assert.ok(server.fixture.poolContents.ip_pool_default.includes('本地备注'));
    await set('#ip-input', '203.0.113.10:443');
    const removeStart = server.requests.length;
    await read('window.__confirmAnswer = false'); await click('[data-action=remove-input]');
    assert.equal(server.requests.slice(removeStart).filter(item => item.method === 'PUT').length, 0);
    await read('window.__confirmAnswer = true'); await click('[data-action=remove-input]');
    await waitForUiRequest(server.requests, removeStart, '/api/pools/ip_pool_default', 'PUT', 200);
    await until('!document.querySelector("[data-action=remove-input]").disabled');
    assert.ok(!server.fixture.poolContents.ip_pool_default.includes('203.0.113.10:443,'));
    assert.ok(server.fixture.poolContents.ip_pool_default.includes('203.0.113.10:8443'));
    assert.ok(server.fixture.poolContents.ip_pool_default.includes('# 保留标题'));
    assert.equal(server.requests.slice(removeStart).filter(item => item.method === 'GET' && item.path === '/api/pools').length, 0);
    await click('.pool-source-actions button:nth-child(2)');
    await set('#remote-url', 'https://list.example.test/ips.txt');
    await click('[aria-label="从远程 URL 加载"]');
    await until('document.querySelector("#ip-input").value.includes("203.0.113.99") && !document.querySelector("[data-action=load-pool]").disabled');
    assert.equal(await read('document.documentElement.scrollWidth > innerWidth'), false);
    assert.ok(await read('document.querySelector(".dashboard-pool-card").getBoundingClientRect().height < 540'));
    await capture('final-' + width);
    await click('[data-page=config]');
    await until('Boolean(document.querySelector("#cfg-probe-ipv4"))');
    assert.equal(await read('document.querySelector("#cfg-probe-ipv4").value'), '');
    await click('[aria-label="版本更新历史"]');
    await until('!document.querySelector("#version-notes").hidden');
    assert.equal(await read('document.querySelector("#version-notes").getBoundingClientRect().left < 0 || document.querySelector("#version-notes").getBoundingClientRect().right > innerWidth'), false);
    results.push({ width, passed: true });
    console.log(`PASS ${width}px: compact layout, help, geo/colo, lossless filtering, result selection, one-PUT append, exact removal, file/URL imports`);
  }
} catch (error) {
  process.exitCode = 1; results.push({ passed: false, error: error.stack }); console.error(error);
} finally {
  writeFileSync(join(out, 'results.json'), JSON.stringify(results, null, 2));
  await browser?.close(); await server.close();
}
